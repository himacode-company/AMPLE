'use strict';
// Every folder in htdocs becomes its own site:  htdocs\shop  ->  http://shop.localhost
// (*.localhost reaches this PC in every modern browser, no hosts file, no admin.)
//
// apache\conf\ample-sites.conf is generated on every start:
//   - one explicit <VirtualHost> per folder (correct DOCUMENT_ROOT; public\ for Laravel etc.)
//   - a catch-all *.localhost host, so a folder created while Apache runs works immediately
//   - the same on port 443 when HTTPS is on (ample https on)
const fs = require('fs');
const path = require('path');
const P = require('./paths');
const settings = require('./settings');

const SITES_CONF = path.join(P.apache, 'conf', 'ample-sites.conf');
// Valid host label: letters, digits, hyphens (no spaces, underscores or other characters).
const VALID = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/i;

// Which folder the site should serve, and what kind of project it is.
function detect(dir) {
  const has = (...p) => fs.existsSync(path.join(dir, ...p));
  if (has('artisan') && has('public', 'index.php')) return { framework: 'Laravel', web: 'public' };
  if (has('bin', 'console') && has('public', 'index.php')) return { framework: 'Symfony', web: 'public' };
  if (has('wp-config.php') || has('wp-load.php')) return { framework: 'WordPress', web: '' };
  if (has('public', 'index.php')) return { framework: 'PHP (public/)', web: 'public' };
  if (has('web', 'index.php')) return { framework: 'PHP (web/)', web: 'web' };
  if (has('public_html')) return { framework: 'PHP (public_html/)', web: 'public_html' };
  return { framework: has('composer.json') ? 'Composer project' : 'folder', web: '' };
}

// Suggested valid name for a folder that can't be used as a host name.
const suggest = (name) => name.toLowerCase().replace(/[\s_]+/g, '-').replace(/[^a-z0-9-]/g, '').replace(/^-+|-+$/g, '') || null;

function list() {
  if (!fs.existsSync(P.htdocs)) return { sites: [], skipped: [] };
  const sites = [], skipped = [];
  const s = settings.load();
  const port = s.ports.http === 80 ? '' : `:${s.ports.http}`;
  const sport = s.ports.https === 443 ? '' : `:${s.ports.https}`;
  for (const ent of fs.readdirSync(P.htdocs, { withFileTypes: true })) {
    if (!ent.isDirectory() || ent.name.startsWith('.')) continue;
    if (!VALID.test(ent.name)) {
      skipped.push({ name: ent.name, suggestion: suggest(ent.name) });
      continue;
    }
    const dir = path.join(P.htdocs, ent.name);
    const d = detect(dir);
    const host = `${ent.name.toLowerCase()}.localhost`;
    sites.push({
      name: ent.name, host, dir, docroot: d.web ? path.join(dir, d.web) : dir, framework: d.framework,
      url: `http://${host}${port}/`, httpsUrl: s.https ? `https://${host}${sport}/` : null,
    });
  }
  return { sites, skipped };
}

function vhost(port, name, docroot, aliases, ssl) {
  const lines = [`<VirtualHost *:${port}>`, `    ServerName ${name}`];
  if (aliases) lines.push(`    ServerAlias ${aliases}`);
  lines.push(docroot.virtual ? `    VirtualDocumentRoot "${docroot.virtual}"` : `    DocumentRoot "${P.fwd(docroot)}"`);
  if (ssl) {
    lines.push('    SSLEngine on', `    SSLCertificateFile "${P.fwd(ssl.cert)}"`, `    SSLCertificateKeyFile "${P.fwd(ssl.key)}"`);
  }
  lines.push('</VirtualHost>');
  return lines.join('\n');
}

// Write apache\conf\ample-sites.conf. ssl = { cert, key } when HTTPS is on.
function writeConf(ssl = null) {
  const s = settings.load();
  const { sites, skipped } = list();
  const blocks = [
    '# GENERATED by AMPLE on every start: one site per folder in htdocs.',
    '# Your own virtual hosts go in apache\\conf\\vhosts\\ (never overwritten).',
    '',
  ];
  const ports = [[s.ports.http, null]];
  if (ssl) {
    // (SSLSessionCache is set in httpd.conf, so mod_ssl never warns.)
    blocks.push(`Listen 127.0.0.1:${s.ports.https}`, 'SSLProtocol -all +TLSv1.2 +TLSv1.3', '');
    ports.push([s.ports.https, ssl]);
  }
  for (const [port, cert] of ports) {
    // HTTPS: the first host of the port refuses unknown host names (DNS-rebinding protection;
    // the plain-HTTP one is in httpd.conf, before your own virtual hosts).
    if (cert) {
      blocks.push([
        `<VirtualHost *:${port}>`, '    ServerName unknown-host.ample.invalid',
        '    SSLEngine on', `    SSLCertificateFile "${P.fwd(cert.cert)}"`, `    SSLCertificateKeyFile "${P.fwd(cert.key)}"`,
        '    <Location "/">', '        Require all denied', '    </Location>',
        '</VirtualHost>',
      ].join('\n'));
    }
    blocks.push(vhost(port, 'localhost', P.htdocs, '127.0.0.1', cert));
    for (const site of sites) blocks.push(vhost(port, site.host, site.docroot, null, cert));
    // Catch-all: a NEW folder works right away (%-2 = the part before ".localhost").
    blocks.push(vhost(port, 'any.localhost', { virtual: `${P.fwd(P.htdocs)}/%-2` }, '*.localhost', cert));
    blocks.push('');
  }
  if (skipped.length) {
    blocks.push('# Folders that are not valid site names (rename them to use NAME.localhost):');
    for (const k of skipped) blocks.push(`#   "${k.name}"${k.suggestion ? `  ->  ${k.suggestion}` : ''}`);
  }
  fs.writeFileSync(SITES_CONF, blocks.join('\n') + '\n');
  return { sites, skipped, conf: SITES_CONF };
}

// A folder directly inside htdocs, found without caring about upper / lower case.
function findFolder(name) {
  if (!fs.existsSync(P.htdocs)) return null;
  const hit = fs.readdirSync(P.htdocs, { withFileTypes: true })
    .find((e) => e.isDirectory() && e.name.toLowerCase() === String(name).toLowerCase());
  return hit ? hit.name : null;
}

// "ample sites new NAME": htdocs\NAME with a small start page. Works at once at
// http://NAME.localhost (the catch-all host); no restart needed.
function create(name) {
  name = String(name || '').trim();
  if (!VALID.test(name)) {
    throw new Error(`"${name}" can't be a site name: use English letters, digits and hyphens${suggest(name) ? ` (e.g. ${suggest(name)})` : ''}`);
  }
  if (findFolder(name)) throw new Error(`htdocs\\${findFolder(name)} already exists`);
  const dir = path.join(P.htdocs, name);
  fs.mkdirSync(dir, { recursive: true });
  // name is checked above (letters, digits, hyphens), so it is safe inside the page.
  fs.writeFileSync(path.join(dir, 'index.php'), [
    '<?php',
    `// ${name}: a new AMPLE site. Replace this file with your project.`,
    '?>',
    '<!doctype html>',
    '<html lang="en"><head><meta charset="utf-8"><title>' + name + '</title>',
    '<style>body{font:16px/1.6 "Segoe UI",system-ui,sans-serif;background:#f6f4f0;color:#1c1a17;display:grid;place-items:center;min-height:100vh;margin:0}',
    'main{background:#fff;border:1px solid #e3ded5;border-radius:14px;padding:32px 40px;text-align:center}h1{margin:0 0 6px;color:#b35a0c}code{background:#f1ede6;padding:2px 6px;border-radius:6px}</style>',
    '</head><body><main>',
    `<h1>${name}</h1>`,
    '<p>It works. This page is <code><?= htmlspecialchars(__FILE__) ?></code></p>',
    '<p>PHP <?= PHP_VERSION ?></p>',
    '</main></body></html>',
    '',
  ].join('\n'));
  require('./logger').log('Sites', 'NEW', `htdocs\\${name} -> http://${name.toLowerCase()}.localhost/`);
  return list().sites.find((x) => x.name === name) || { name };
}

// "ample sites rename OLD NEW": rename a folder in htdocs (e.g. "Old Project" -> old-project).
// Only a folder name directly inside htdocs is accepted, never a path.
function rename(from, to) {
  from = String(from || ''); to = String(to || '').trim();
  if (!from || from !== path.basename(from) || from === '.' || from === '..') throw new Error(`"${from}" is not a folder name in htdocs`);
  const actual = findFolder(from);
  if (!actual || actual !== from) throw new Error(`htdocs\\${from} does not exist`);
  if (!VALID.test(to)) throw new Error(`"${to}" can't be a site name: use English letters, digits and hyphens`);
  const other = findFolder(to);
  if (other && other.toLowerCase() !== from.toLowerCase()) throw new Error(`htdocs\\${other} already exists`);
  try {
    fs.renameSync(path.join(P.htdocs, from), path.join(P.htdocs, to));
  } catch (e) {
    if (['EPERM', 'EBUSY', 'EACCES'].includes(e.code)) {
      throw new Error(`Windows did not allow renaming "${from}": a program is using it (VS Code, a terminal, Explorer...). Close it and try again.`);
    }
    throw e;
  }
  require('./logger').log('Sites', 'RENAME', `htdocs\\${from} -> htdocs\\${to}`);
  return list().sites.find((x) => x.name === to) || { name: to };
}

// Sites whose folder Apache does not serve correctly yet: a project that must be served from a
// sub-folder (Laravel's public\ ...) created while Apache was running; only a restart writes
// its own host. A plain folder is already served right by the catch-all host, so it is never
// listed. Empty = nothing to apply.
function pendingChanges() {
  let conf = '';
  try { conf = fs.readFileSync(SITES_CONF, 'utf8'); } catch { /* not generated yet */ }
  return list().sites
    .filter((x) => x.docroot !== x.dir && !conf.includes(`DocumentRoot "${P.fwd(x.docroot)}"`))
    .map((x) => x.name);
}

// Your own virtual hosts (apache\conf\vhosts\*.conf), read-only: name, aliases, folder.
function ownHosts() {
  if (!fs.existsSync(P.vhosts)) return [];
  const out = [];
  for (const file of fs.readdirSync(P.vhosts).filter((f) => /\.conf$/i.test(f))) {
    let text = '';
    try { text = fs.readFileSync(path.join(P.vhosts, file), 'utf8'); } catch { continue; }
    for (const block of text.split(/<VirtualHost\b/i).slice(1)) {
      const body = block.split(/<\/VirtualHost>/i)[0];
      const get = (key) => ((body.match(new RegExp(`^\\s*${key}\\s+"?([^"\\r\\n]+)"?`, 'im')) || [])[1] || '').trim();
      const port = ((block.match(/^[^>]*:(\d+)/) || [])[1]) || '';
      const name = get('ServerName');
      if (!name) continue;
      out.push({ file, name, aliases: get('ServerAlias'), docroot: get('DocumentRoot'), https: /^\s*SSLEngine\s+on/im.test(body), port });
    }
  }
  return out;
}

module.exports = { list, writeConf, detect, create, rename, pendingChanges, ownHosts, SITES_CONF, VALID };

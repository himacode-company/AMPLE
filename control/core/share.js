'use strict';
// "ample share SITE": a public https link to ONE site, through a Cloudflare Quick Tunnel.
// No Cloudflare account, no router settings: cloudflared (signed by Cloudflare) connects OUT
// to Cloudflare, which gives a random https://xxxx.trycloudflare.com address.
//
//   visitor -> Cloudflare -> cloudflared on this PC -> Apache's private door (127.0.0.1:share)
//
// The door (apache\conf\ample-share.conf) serves the shared site ONLY and refuses
// phpMyAdmin, the dashboard and Mailpit: requests through the tunnel come from this PC, so
// "Require local" alone would let anyone in. Optional password (HTTP Basic, bcrypt).
// For demos and tests (show a client, try on a phone, receive a webhook), not for hosting.
const fs = require('fs');
const path = require('path');
const { spawn, spawnSync } = require('child_process');
const P = require('./paths');
const settings = require('./settings');
const { log } = require('./logger');

const EXE = P.p('cloudflared', 'cloudflared.exe');
const CONF = path.join(P.apache, 'conf', 'ample-share.conf');
const STATE = path.join(P.run, 'share.json');
const HTPASSWD = path.join(P.run, 'share.htpasswd');
const TUNNEL_LOG = path.join(P.logs, 'share', 'cloudflared.log');
const ACCESS_LOG = path.join(P.logs, 'share', 'access.log');
const USER = 'guest';
const URL_RE = /https:\/\/[a-z0-9-]+\.trycloudflare\.com/i;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const alive = (pid) => { if (!pid) return false; try { process.kill(pid, 0); return true; } catch (e) { return e.code === 'EPERM'; } };
const readState = () => { try { return JSON.parse(fs.readFileSync(STATE, 'utf8')); } catch { return null; } };

function installed() { return fs.existsSync(EXE); }

// First use: download cloudflared (checksum from components.json).
async function install(say = () => {}) {
  const comps = JSON.parse(fs.readFileSync(P.componentsFile, 'utf8'));
  await require('./download').install('cloudflared', comps.cloudflared, say);
  return installed();
}

// The door. site = null writes an empty file (nothing shared).
function writeConf(site, withPassword) {
  fs.mkdirSync(path.dirname(CONF), { recursive: true });
  if (!site) {
    fs.writeFileSync(CONF, '# Nothing is shared right now (ample share).\n');
    return;
  }
  const port = settings.load().ports.share;
  fs.mkdirSync(path.dirname(ACCESS_LOG), { recursive: true }); // Apache refuses a log in a missing folder
  const lines = [
    `# GENERATED by AMPLE while "${site.name}" is shared publicly (ample share). Removed when sharing stops.`,
    `Listen 127.0.0.1:${port}`,
    `<VirtualHost 127.0.0.1:${port}>`,
    `    ServerName ${site.host}`,
    `    DocumentRoot "${P.fwd(site.docroot)}"`,
    '    # The visitor came over https (Cloudflare): tell PHP, so frameworks build https links.',
    '    SetEnvIf X-Forwarded-Proto "^https$" HTTPS=on',
    `    CustomLog "${P.fwd(ACCESS_LOG)}" ample`,
  ];
  if (withPassword) {
    lines.push(
      '    <Location "/">',
      '        AuthType Basic',
      '        AuthName "AMPLE shared site"',
      `        AuthUserFile "${P.fwd(HTPASSWD)}"`,
      '        Require valid-user',
      '    </Location>',
    );
  }
  lines.push(
    "    # AMPLE's own tools are NEVER reachable through the public link.",
    '    <LocationMatch "^/+(phpmyadmin|ample|ample-pma|mailpit)(/|$)">',
    '        Require all denied',
    '    </LocationMatch>',
    '</VirtualHost>',
    '',
  );
  fs.writeFileSync(CONF, lines.join('\n'));
}

// { active, site, url, port, started, password }  (a dead tunnel is cleaned up here)
function status() {
  const st = readState();
  if (st && alive(st.pid)) return { active: true, installed: installed(), site: st.site, url: st.url, port: st.port, started: st.started, password: !!st.password };
  if (st) cleanup();
  return { active: false, installed: installed() };
}

function cleanup() {
  fs.rmSync(STATE, { force: true });
  fs.rmSync(HTPASSWD, { force: true });
  try { if (fs.existsSync(CONF) && fs.readFileSync(CONF, 'utf8').includes('<VirtualHost')) writeConf(null); } catch { /* next start */ }
}

// Stop the tunnel at once (used when the panel closes or Apache stops). The door stays in
// Apache until its next restart: it is 127.0.0.1-only and refuses the tools, so it is harmless.
function killTunnel() {
  const st = readState();
  if (st && alive(st.pid)) spawnSync('taskkill', ['/PID', String(st.pid), '/T', '/F'], { stdio: 'ignore' });
  if (st) { cleanup(); log('Share', 'STOP', `public link for ${st.site} closed`); }
  return !!st;
}

async function restartApache() {
  const services = require('./services');
  if ((await services.status('apache')).running) await services.restart('apache');
}

async function start(name, { password = null } = {}) {
  if (!installed()) throw Object.assign(new Error('cloudflared is not downloaded yet'), { code: 'NOT_INSTALLED' });
  const services = require('./services');
  const site = require('./sites').list().sites.find((x) => x.name === name);
  if (!site) throw new Error(`There is no site "${name}" in htdocs (see: ample sites)`);
  if (!(await services.status('apache')).running) throw new Error('Apache is not running. Start it first: ample start apache');
  if (password !== null && (typeof password !== 'string' || password.length < 4 || password.length > 128)) {
    throw new Error('The password must be 4 to 128 characters');
  }
  if (status().active) await stop();

  // Password file: written by Apache's own htpasswd (bcrypt); the password goes through
  // standard input, never on a command line.
  if (password) {
    fs.mkdirSync(path.dirname(HTPASSWD), { recursive: true });
    const r = spawnSync(path.join(P.apache, 'bin', 'htpasswd.exe'), ['-i', '-B', '-c', HTPASSWD, USER],
      { input: password + '\n', encoding: 'utf8', windowsHide: true });
    if (r.status !== 0) throw new Error('Could not create the password file: ' + (r.stderr || r.stdout || '').trim());
  }
  writeConf(site, !!password);
  try {
    await restartApache(); // also checks the config ("httpd -t")
  } catch (e) {
    writeConf(null);
    fs.rmSync(HTPASSWD, { force: true });
    await restartApache().catch(() => {});
    throw e;
  }

  // The tunnel runs on its own (detached), so "ample share" can return; its output goes to a log
  // file, where the public address appears after a few seconds.
  fs.mkdirSync(path.dirname(TUNNEL_LOG), { recursive: true });
  const out = fs.openSync(TUNNEL_LOG, 'w');
  const port = settings.load().ports.share;
  const child = spawn(EXE, ['tunnel', '--url', `http://127.0.0.1:${port}`, '--no-autoupdate'], {
    detached: true, windowsHide: true, stdio: ['ignore', out, out],
  });
  child.unref();
  fs.closeSync(out);

  let url = null;
  for (let i = 0; i < 90 && !url; i++) {
    await sleep(500);
    if (!alive(child.pid)) break;
    const text = fs.readFileSync(TUNNEL_LOG, 'utf8');
    const m = text.match(URL_RE);
    if (m) url = m[0];
  }
  if (!url) {
    spawnSync('taskkill', ['/PID', String(child.pid), '/T', '/F'], { stdio: 'ignore' });
    const tail = (fs.existsSync(TUNNEL_LOG) ? fs.readFileSync(TUNNEL_LOG, 'utf8') : '').trim().split(/\r?\n/).slice(-6).join('\n');
    cleanup();
    await restartApache().catch(() => {});
    throw new Error(`Cloudflare did not give a public address within 45 s (internet connection?).\n${tail}`);
  }
  const state = { site: site.name, url, pid: child.pid, port, started: Date.now(), password: !!password };
  fs.mkdirSync(path.dirname(STATE), { recursive: true });
  fs.writeFileSync(STATE, JSON.stringify(state, null, 2));
  log('Share', 'START', `${site.name} is public at ${url}${password ? ' (password)' : ''}`);
  return { active: true, site: site.name, url, port, started: state.started, password: !!password, user: password ? USER : null };
}

async function stop() {
  const was = killTunnel();
  writeConf(null);
  await restartApache().catch(() => {});
  return { stopped: was };
}

module.exports = { status, start, stop, install, installed, killTunnel, writeConf, EXE, CONF, USER };
